-- Prime Sport: shared event catalogue (sports, organizers, events).
-- The app reads these tables with the public (anon) key and caches them in its on-device
-- SQLite database. Saved events and registrations stay on the device until sign-in exists.
-- Events are added and edited in the Supabase dashboard (Table Editor) for now.

create table public.sports (
  sport_id integer primary key,
  name text not null unique,
  icon text not null,
  status text not null default 'active' check (status in ('active', 'inactive'))
);

create table public.organizers (
  organizer_id integer generated by default as identity primary key,
  name text not null,
  logo text,
  description text,
  verified boolean not null default false
);

create table public.events (
  event_id integer generated by default as identity primary key,
  title text not null check (length(title) between 1 and 200),
  sport_id integer not null references public.sports (sport_id),
  organizer_id integer not null references public.organizers (organizer_id),
  image text,
  date date not null,
  start_time time not null,
  location text not null,
  city text not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  description text not null default '',
  price integer not null default 0 check (price >= 0),
  verified boolean not null default false,
  status text not null default 'upcoming'
    check (status in ('upcoming', 'ongoing', 'completed', 'cancelled')),
  is_sample boolean not null default false,
  -- Unpublished events stay in the dashboard and never reach the app.
  is_published boolean not null default true,
  last_updated timestamptz not null default now()
);
create index events_date_idx on public.events (date);
create index events_sport_idx on public.events (sport_id);
create index events_organizer_idx on public.events (organizer_id);
create index events_city_idx on public.events (city);

-- Keep last_updated honest whenever an event is edited.
create function public.touch_last_updated() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.last_updated := now();
  return new;
end;
$$;
create trigger events_touch_last_updated before update on public.events
  for each row execute function public.touch_last_updated();

-- Public read-only access; only the dashboard (service role) can write.
alter table public.sports enable row level security;
alter table public.organizers enable row level security;
alter table public.events enable row level security;

create policy "Anyone can read active sports" on public.sports
  for select to anon, authenticated using (status = 'active');
create policy "Anyone can read organizers" on public.organizers
  for select to anon, authenticated using (true);
create policy "Anyone can read published events" on public.events
  for select to anon, authenticated using (is_published);
